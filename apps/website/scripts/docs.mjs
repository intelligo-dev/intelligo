/**
 * The docs that must not be written by hand.
 *
 * Reference material — a page per package, the CLI, the registry's
 * install order and its config seams — is generated from the files that
 * are the truth (package READMEs and manifests, the CLI's own doc
 * comments and template manifest, packages/registry), so it
 * cannot describe an API, a command or a file that no longer exists.
 * Hand-written pages keep their code honest through snippets: a fenced
 * block right after `<!-- snippet: path#symbol -->` is replaced with that
 * declaration from the real file.
 *
 * The ADRs are the maintainers' record, not reader documentation: a
 * reference to one is stripped from everything generated here, and the
 * docs test refuses one in a hand-written page.
 *
 * Pure functions over the repository root. `sync-framework.mjs` writes
 * what they return; tests/architecture/docs.test.ts fails when what is
 * committed differs, so a stale page is a red build, not a quiet lie.
 */
